#!/usr/bin/env python3
"""把 docs/用户手册.md 注入 archive/web/index.html 的「使用说明」弹窗。

为什么要生成而不是手抄：手册改一句、弹窗里那句就过期，而弹窗是客户在 App 里
唯一能看到的说明。手抄两次之后必然出现「PDF 上写着 A、App 里写着 B」。
这份脚本让 docs/用户手册.md 成为唯一真相，App 内置说明只是它的一种渲染。

用法：
    tools/gen_help.py            # 写入 index.html
    tools/gen_help.py --check    # 只校验是否同步（CI / 测试用），不同步返回 1

标记约定：index.html 里 helpModal 的内容由下面两个注释包裹，
脚本只替换这两个标记之间的部分，其余 HTML 一个字都不动。
"""
from __future__ import annotations

import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MD = ROOT / "docs" / "用户手册.md"
INDEX = ROOT / "archive" / "web" / "index.html"

BEGIN = "<!-- BEGIN help-manual (generated by tools/gen_help.py from docs/用户手册.md, do not edit by hand) -->"
END = "<!-- END help-manual -->"

# 手册里的 h1 是文档名，弹窗标题栏已经有「使用说明」，所以要降级而不是重复。
# h2 → h4，h3 → h5：沿用 theme.css 里既有的 .help h4 章节样式。
def render_body(md_text: str) -> str:
    try:
        import markdown
    except ImportError:  # pragma: no cover
        sys.exit("需要 python-markdown：pip install markdown")

    # 去掉首个 h1
    md_text = re.sub(r"\A#\s+.*?\n", "", md_text, count=1)

    body = markdown.markdown(
        md_text,
        extensions=["tables", "fenced_code", "sane_lists"],
        output_format="html5",
    )

    # 标题降级（从深到浅，避免连环替换）
    body = re.sub(r"<h3>(.*?)</h3>", r"<h5>\1</h5>", body, flags=re.S)
    body = re.sub(r"<h2>(.*?)</h2>", r"<h4>\1</h4>", body, flags=re.S)

    # 目录锚点用不到，id 留着也没坏处；但 <hr> 在这里只是分隔线，保留。
    return body.strip()


def build_block(md_text: str) -> str:
    body = render_body(md_text)
    return (
        '<div class="modal-box help">\n'
        "  <h3>❓ 使用说明</h3>\n"
        f"  {BEGIN}\n"
        f"{body}\n"
        f"  {END}\n"
        '  <div class="modal-actions"><button class="button" onclick="closeHelp()">知道了</button></div>\n'
        "</div>"
    )


def _match_close(html_text: str, open_end: int) -> int:
    """从 open_end 开始，返回与起始 div 配对的 </div> 之后的下标。

    不能用正则的非贪婪匹配：弹窗内部还有 modal-actions 等嵌套 div，
    第一个 </div></div> 会在内层就停下，替换后整个页面结构就错位了。
    """
    depth = 1
    i = open_end
    tag = re.compile(r"<div\b|</div>", re.I)
    while depth:
        m = tag.search(html_text, i)
        if not m:
            sys.exit("index.html 的 #helpModal 结束标签不配对")
        depth += -1 if m.group(0).startswith("</") else 1
        i = m.end()
    return i


def splice(index_html: str, block: str) -> str:
    """把新的 modal-box help 换进 #helpModal，保留外层 div 与 onclick。"""
    open_m = re.search(r'<div id="helpModal"[^>]*>', index_html)
    if not open_m:
        sys.exit("index.html 里找不到 #helpModal，标记结构变了？")
    end = _match_close(index_html, open_m.end())
    return index_html[: open_m.end()] + block + index_html[end - len("</div>"):]


def main() -> int:
    md_text = MD.read_text(encoding="utf-8")
    block = build_block(md_text)
    current = INDEX.read_text(encoding="utf-8")
    updated = splice(current, block)

    if "--check" in sys.argv:
        if updated != current:
            print("使用说明未同步：请运行 tools/gen_help.py", file=sys.stderr)
            return 1
        print("使用说明与 docs/用户手册.md 一致")
        return 0

    if updated == current:
        print("无变化")
        return 0
    INDEX.write_text(updated, encoding="utf-8")
    print(f"已写入 {INDEX.relative_to(ROOT)}（{len(block)} 字节的说明正文）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
